    private async Task AcquireAndInjectTokenAsync()
    {
        var tenants = _appInfoVm.FullConfig.IntuneTenants
            .Where(t => !string.IsNullOrWhiteSpace(t.Key) && Guid.TryParse(t.Key, out _))
            .ToList();

        if (tenants.Count == 0)
        {
            AddLog("[WARN] No Intune tenants configured. Skipping MSAL auth (PS-side auth will be used).", "Warning");
            AppLogger.Warn("[Run] No Intune tenants configured -- skipping MSAL auth");
            return;
        }

        var hwnd = WindowHelper.GetMainWindowHwnd();

        MsalTokenResult? lastInjected = null;

        foreach (var tenant in tenants)
        {
            var displayName = !string.IsNullOrWhiteSpace(tenant.Name) ? tenant.Name : tenant.Key;

            var conn = IntuneConnections.FirstOrDefault(c =>
                string.Equals(c.TenantId, tenant.Key, StringComparison.OrdinalIgnoreCase));
            if (conn is not null && !conn.IsEnabled)
            {
                conn.State = ConnectionState.Skipped;
                conn.StatusText = "Skipped";
                AddLog($"[AUTH] {displayName}: skipped (disabled for this run).", "Verbose");
                continue;
            }

            try
            {
                AddLog($"[AUTH] Acquiring token for {displayName}...", "Info");
                AppLogger.Info($"[Run] Acquiring MSAL token for tenant {displayName} ({tenant.Key})");

                await _authService.InitializeForTenantAsync(tenant, hwnd);

                var token = await _authService.AcquireTokenAsync();

                _tenantTokens[tenant.Key] = token;
                lastInjected = token;

                var matchedConn = IntuneConnections.FirstOrDefault(c =>
                    string.Equals(c.TenantId, tenant.Key, StringComparison.OrdinalIgnoreCase));
                if (matchedConn is not null)
                    ConnectionChecker.ApplyTokenStatus(matchedConn, token, graphReachable: true);

                var who = !string.IsNullOrEmpty(token.UserPrincipalName)
                    ? token.UserPrincipalName
                    : "app credentials";
                AddLog($"[AUTH] {displayName}: token acquired ({who}), expires {token.ExpiresOnUtc:HH:mm:ss} UTC", "Info");
                AppLogger.Info($"[Run] {displayName}: token acquired ({who}), expires {token.ExpiresOnUtc:HH:mm:ss} UTC");
            }
            catch (OperationCanceledException)
            {
                AddLog($"[AUTH] Authentication cancelled for {displayName}.", "Warning");
                AppLogger.Warn($"[Run] Authentication cancelled for tenant {displayName}");
                throw; // propagate to abort the run
            }
            catch (Exception ex)
            {
                AddLog($"[AUTH] {displayName}: MSAL authentication failed - {ex.Message}", "Error");
                AppLogger.Error($"[Run] {displayName}: MSAL authentication failed: {ex.Message}");
            }
        }

        // Record the last acquired token for the UI expiry countdown. No pool
        // injection: each tenant's PackageAsync injects its OWN token per pipeline
        // (InjectMsalApp) on the run's dedicated pool -- a pool-level inject here
        // only ever seeded the ambient pool (which the run doesn't use) with the
        // last tenant's token, so it was vestigial.
        if (lastInjected is not null)
        {
            _lastToken = lastInjected;
            StartTokenTimer();
        }
        else
        {
            AddLog("[AUTH] No tokens acquired. Falling back to PowerShell-side authentication.", "Warning");
            AppLogger.Warn("[Run] No MSAL tokens acquired for any tenant");
        }
    }

