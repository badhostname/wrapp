/// <summary>
/// Phase-event consumption + per-package progress accounting for
/// <see cref="RunViewModel"/>. Owns the <c>OnPhaseChanged</c> dispatcher
/// (Invoke-WrappIntune / Invoke-WrappSccm phase events &#x2192; UI updates)
/// and its helpers: package lookup, progress recalculation, log colour
