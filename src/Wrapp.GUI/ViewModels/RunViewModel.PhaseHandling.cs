    private void AddLog(string line, string color = "Default")
    {
        lock (_logLock)
        {
            LogLines.Add(new LogEntry { Content = line, ColorCode = color });
        }
    }

    private const string LogInitPrefix = "[INFO] Log initialized: ";

    private void AddLogFromRaw(string raw)
    {
        // Progress lines update the phase detector but are not shown in the log
        if (raw.StartsWith("[PROG:"))
        {
            _phaseDetector.ProcessLine(raw);
            return;
        }

        // Capture the actual log file path reported by the PS module
        if (raw.StartsWith(LogInitPrefix))
        {
            _actualLogFilePath = raw[LogInitPrefix.Length..].Trim();
            OnPropertyChanged(nameof(LogFilePath));
        }

        string color = raw.StartsWith("[ERROR]")    ? "Error"
                     : raw.StartsWith("[WARN]")     ? "Warning"
                     : raw.StartsWith("[INFO]")     ? "Info"
                     : raw.StartsWith("[VERB]")     ? "Verbose"
                     : raw.StartsWith("[CANCEL")    ? "Warning"
                     : "Default";
        AddLog(raw, color);
    }
