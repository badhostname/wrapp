    private PackageProgress? FindPackage(string? name)
    {
        if (string.IsNullOrEmpty(name)) return null;
        return PackageProgressItems.FirstOrDefault(
            p => string.Equals(p.PackageName, name.Trim(), StringComparison.OrdinalIgnoreCase));
    }

    private PackageProgress? FindActivePackage()
    {
        return FindPackage(_activePackageName);
    }

    /// <summary>
    /// Recalculates progress with sub-step interpolation.
    /// Sub-step percent (0-100) is mapped into the current step's fraction.
    /// </summary>
    private void RecalcProgress(PackageProgress pkg)
    {
        if (pkg.TotalSteps <= 0) return;
        double stepFraction = 100.0 / pkg.TotalSteps;
        pkg.ProgressPercent = pkg.CompletedSteps * stepFraction
            + (pkg.SubStepPercent / 100.0) * stepFraction;
        PushProgressToJobTracker();
    }

    /// <summary>Aggregates progress across all running packages and updates the job tracker.</summary>
    private void PushProgressToJobTracker()
    {
        if (!_currentRunJob.IsActive) return;
        var running = PackageProgressItems.Where(p => p.Outcome == PackageOutcome.Running).ToList();
        if (running.Count == 0) return;
        _currentRunJob.SetProgress((int)running.Average(p => p.ProgressPercent));
        var current = running.FirstOrDefault(p => !string.IsNullOrEmpty(p.CurrentStepName));
        if (current is not null)
            _currentRunJob.SetStatus($"Packaging: {current.CurrentStepName}");
    }

    private void SetGlobalSubStep(string stepName, string statusText, int subPercent)
    {
        foreach (var pkg in PackageProgressItems)
        {
            if (!InCurrentPass(pkg)) continue;
            if (pkg.Outcome is PackageOutcome.Skipped or PackageOutcome.Failed) continue;
            pkg.CurrentStepName = statusText;
            pkg.SubStepPercent = subPercent;
            RecalcProgress(pkg);
        }
    }

    /// <summary>
    /// True when <paramref name="pkg"/> belongs to the current per-tenant/site
    /// PackageAsync pass (or when no pass scoping is set). Keeps one tenant's
    /// "global" steps + finalization from touching another tenant's packages.
    /// </summary>
    private bool InCurrentPass(PackageProgress pkg)
        => _currentPassPackages.Count == 0 || _currentPassPackages.Contains(pkg.PackageName);

    private void SetGlobalStep(string stepName, StepState state, string? targetFilter = null)
    {
        foreach (var pkg in PackageProgressItems)
        {
            if (!InCurrentPass(pkg))
                continue;

            if (targetFilter is not null &&
                !pkg.Target.StartsWith(targetFilter, StringComparison.OrdinalIgnoreCase))
                continue;

            SetStep(pkg, stepName, state);
        }
    }

    private void SetStep(PackageProgress pkg, string stepName, StepState state)
    {
        var step = pkg.Steps.FirstOrDefault(
            s => string.Equals(s.Name, stepName, StringComparison.OrdinalIgnoreCase));
        if (step is null) return;

        step.State = state;

        if (state == StepState.Running)
            pkg.CurrentStepName = stepName;

        pkg.CompletedSteps = pkg.Steps.Count(s => s.State is StepState.Succeeded or StepState.Skipped);
        pkg.ProgressPercent = pkg.TotalSteps > 0
            ? (double)pkg.CompletedSteps / pkg.TotalSteps * 100.0
            : 0.0;
    }

    private void FinalizeAllPackages()
    {
        foreach (var pkg in PackageProgressItems)
        {
            // Only finalize packages processed in the current tenant/site pass.
            // A multi-tenant run fires OrchestratorCompleted once per tenant; without
            // this scope the first tenant's completion would finalize packages that
            // belong to later tenants (which are still Pending) as "Succeeded".
            if (!InCurrentPass(pkg))
                continue;

            // Don't override packages already marked as Skipped, Failed, or Cancelled
            if (pkg.Outcome is PackageOutcome.Running or PackageOutcome.Pending)
            {
                bool hasFailedStep = pkg.Steps.Any(s => s.State == StepState.Failed);
                bool hasSucceededStep = pkg.Steps.Any(s => s.State == StepState.Succeeded);
                if (hasFailedStep && hasSucceededStep)
                {
                    pkg.Outcome = PackageOutcome.PartialSuccess;
                    var failedNames = string.Join(", ", pkg.Steps.Where(s => s.State == StepState.Failed).Select(s => s.Name));
                    pkg.CurrentStepName = "Partial";
                    pkg.FailureReason = $"Failed: {failedNames}";
                }
                else if (hasFailedStep)
                {
                    pkg.Outcome = PackageOutcome.Failed;
                    var failedNames = string.Join(", ", pkg.Steps.Where(s => s.State == StepState.Failed).Select(s => s.Name));
                    pkg.CurrentStepName = "Failed";
                    pkg.FailureReason = $"Failed: {failedNames}";
                }
                else
                {
                    pkg.Outcome = PackageOutcome.Succeeded;
                    pkg.CurrentStepName = "Complete";
                    // Clear any stale failure detail so a succeeded package's
                    // detail accurately reflects success (defence against any
                    // residual cross-tenant bleed).
                    pkg.FailureReason = string.Empty;
                    pkg.DetailText = string.Empty;
                }
                pkg.ProgressPercent = 100.0;
            }
        }
    }

