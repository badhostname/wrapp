    /// <summary>
    /// Regex phases the module now reports as typed <c>Write-WrappStep</c> events.
    /// While <see cref="_stepEventsOwnProgress"/> is set (the Intune path), these
    /// are driven by <see cref="ApplyStepEvent"/> instead and the regex path is
    /// suppressed to keep a single source of truth per step. Only
    /// <see cref="PhaseId.UploadProgress"/> stays regex-driven: it comes from the
    /// PS progress stream's structured PercentComplete (the [PROG:nn] prefix is
    /// generated by PowerShellService, not scraped prose). The SCCM path leaves
    /// the flag clear, so it keeps using these regexes until its module emits
    /// step events.
    /// </summary>
    private static readonly HashSet<PhaseId> StepEventOwnedPhases = new()
    {
        PhaseId.CollisionCheckStarted, PhaseId.CollisionDetected, PhaseId.CollisionCheckPassed,
        PhaseId.WrappingStarted, PhaseId.WrappingCopying, PhaseId.WrappingCopied,
        PhaseId.WrappingEncoding, PhaseId.WrappingCompleted,
        PhaseId.AppProcessingStarted, PhaseId.AppCreatingStarted, PhaseId.AppCreated,
        PhaseId.UploadMetadata, PhaseId.UploadConstructing, PhaseId.UploadRegistering,
        PhaseId.UploadGraphCreated, PhaseId.UploadContentVersion, PhaseId.UploadFileEntry,
        PhaseId.UploadStorageUriWaiting, PhaseId.UploadStarted,
        PhaseId.UploadCommitting, PhaseId.UploadCommitPolling,
        PhaseId.UploadCommitVersionUpdate, PhaseId.UploadCompleted,
        PhaseId.DependenciesStarted, PhaseId.SupersedenceStarted,
        PhaseId.AssignmentWaiting, PhaseId.AssignmentReady,
        PhaseId.AssignmentCompleted, PhaseId.AssignmentFailed,
        PhaseId.OrchestratorCompleted, PhaseId.Fatal, PhaseId.AppFailed,
    };

    private void OnPhaseChanged(PhaseEvent evt)
    {
        // When the module drives progress via typed step events (Intune),
        // ignore the equivalent regex phases so a single source owns each
        // step. Fine-grained upload / wrapping sub-steps are not gated.
        if (_stepEventsOwnProgress && StepEventOwnedPhases.Contains(evt.Phase))
            return;

        System.Windows.Application.Current.Dispatcher.Invoke(() =>
        {
            switch (evt.Phase)
            {
                case PhaseId.CollisionCheckStarted:
                    SetGlobalStep("Collision Check", StepState.Running);
                    break;

                case PhaseId.CollisionDetected:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        pkg.Outcome = PackageOutcome.Failed;
                        pkg.CurrentStepName = "Collision";
                        pkg.FailureReason = "Already exists in Intune";
                        SetStep(pkg, "Collision Check", StepState.Failed);
                    }
                    break;
                }

                case PhaseId.CollisionCheckPassed:
                    // Mark non-collided packages IN THIS TENANT PASS as passed.
                    foreach (var p in PackageProgressItems)
                    {
                        if (!InCurrentPass(p)) continue;
                        if (p.Outcome != PackageOutcome.Failed)
                            SetStep(p, "Collision Check", StepState.Succeeded);
                    }
                    break;

                case PhaseId.WrappingStarted:
                    SetGlobalStep("Wrapping", StepState.Running);
                    SetGlobalSubStep("Wrapping", "Preparing...", 0);
                    break;

                case PhaseId.WrappingCopying:
                    SetGlobalSubStep("Wrapping", "Copying source files...", 20);
                    break;

                case PhaseId.WrappingCopied:
                    SetGlobalSubStep("Wrapping", "Source files staged", 50);
                    break;

                case PhaseId.WrappingEncoding:
                    SetGlobalSubStep("Wrapping", "Creating .intunewin...", 60);
                    break;

                case PhaseId.WrappingCompleted:
                    SetGlobalSubStep("Wrapping", "Package created", 100);
                    SetGlobalStep("Wrapping", StepState.Succeeded);
                    break;

                case PhaseId.AppProcessingStarted:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        _activePackageName = evt.PackageName;
                        pkg.Outcome = PackageOutcome.Running;
                        pkg.CurrentStepName = "Processing...";
                        pkg.DetailText = string.Empty;
                        pkg.FailureReason = string.Empty;
                        pkg.SubStepPercent = 0;
                        SetStep(pkg, "App Creation", StepState.Running);
                    }
                    break;
                }

                case PhaseId.AppCreatingStarted:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        _activePackageName = evt.PackageName;
                        pkg.Outcome = PackageOutcome.Running;
                        pkg.CurrentStepName = "Creating app...";
                        pkg.DetailText = string.Empty;
                        pkg.FailureReason = string.Empty;
                        pkg.SubStepPercent = 0;
                        SetStep(pkg, "App Creation", StepState.Running);
                    }
                    break;
                }

                // -- IntuneWin32App sub-steps (applied to active package) --
                case PhaseId.UploadMetadata:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Reading .intunewin metadata...";
                        pkg.SubStepPercent = 2;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadConstructing:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Building app body...";
                        pkg.SubStepPercent = 5;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadRegistering:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Registering app in Intune...";
                        pkg.SubStepPercent = 8;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadGraphCreated:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "App registered";
                        pkg.DetailText = evt.Detail ?? string.Empty;
                        pkg.SubStepPercent = 12;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadContentVersion:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Content version created";
                        pkg.SubStepPercent = 15;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadFileEntry:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Preparing file entry...";
                        pkg.SubStepPercent = 18;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadStorageUriWaiting:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Waiting for storage URI...";
                        pkg.SubStepPercent = 22;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadStarted:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Uploading 0%";
                        pkg.SubStepPercent = 25;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadProgress:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null && int.TryParse(evt.Detail, out var pct))
                    {
                        pkg.CurrentStepName = $"Uploading {pct}%";
                        // Map upload 0-100% to sub-step 25-80%
                        pkg.SubStepPercent = 25 + (int)(pct * 0.55);
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadCommitting:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Committing to Intune...";
                        pkg.SubStepPercent = 82;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadCommitPolling:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        var attempt = evt.Detail ?? "?";
                        pkg.CurrentStepName = $"Processing commit (attempt {attempt})...";
                        // Slowly advance from 82% to 95% during polling
                        if (int.TryParse(attempt, out var n))
                            pkg.SubStepPercent = Math.Min(95, 82 + n);
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadCommitVersionUpdate:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Finalizing app version...";
                        pkg.SubStepPercent = 97;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.UploadCompleted:
                {
                    var pkg = FindActivePackage();
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "App creation complete";
                        pkg.SubStepPercent = 100;
                        RecalcProgress(pkg);
                    }
                    break;
                }

                case PhaseId.AppCreated:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "App created";
                        pkg.DetailText = string.Empty;
                        pkg.SubStepPercent = 0;
                        SetStep(pkg, "App Creation", StepState.Succeeded);
                    }
                    break;
                }

                case PhaseId.SccmAppCreating:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        pkg.Outcome = PackageOutcome.Running;
                        pkg.CurrentStepName = "Creating SCCM app...";
                        SetStep(pkg, "App Creation", StepState.Running);
                    }
                    break;
                }

                case PhaseId.DependenciesStarted:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Dependencies...";
                        SetStep(pkg, "Dependencies", StepState.Running);
                    }
                    break;
                }

                case PhaseId.SupersedenceStarted:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                        pkg.CurrentStepName = "Supersedence...";
                    break;
                }

                case PhaseId.AssignmentWaiting:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Waiting for availability...";
                        SetStep(pkg, "Assignment", StepState.Running);
                    }
                    break;
                }

                case PhaseId.AssignmentReady:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Assigning...";
                    }
                    break;
                }

                case PhaseId.AssignmentCompleted:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        var detail = evt.Detail ?? "";
                        bool hasFailed = detail.Contains(", 0 failed") ? false : detail.Contains("failed");
                        if (hasFailed)
                        {
                            pkg.CurrentStepName = $"Assignments: {detail}";
                            pkg.DetailText = detail;
                            SetStep(pkg, "Assignment", StepState.Failed);
                        }
                        else
                        {
                            pkg.CurrentStepName = $"Assignments: {detail}";
                            SetStep(pkg, "Assignment", StepState.Succeeded);
                        }
                    }
                    break;
                }

                case PhaseId.AssignmentFailed:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        pkg.CurrentStepName = "Assignment failed";
                        SetStep(pkg, "Assignment", StepState.Failed);
                    }
                    break;
                }

                case PhaseId.SccmDeploymentsStarted:
                    SetGlobalStep("Content Distribution", StepState.Running, "SCCM");
                    break;

                case PhaseId.AppFailed:
                {
                    var pkg = FindPackage(evt.PackageName);
                    if (pkg is not null)
                    {
                        pkg.Outcome = PackageOutcome.Failed;
                        pkg.FailureReason = evt.Detail ?? "Unknown error";
                        pkg.CurrentStepName = "Failed";
                    }
                    break;
                }

                case PhaseId.OrchestratorCompleted:
                    FinalizeAllPackages();
                    break;

                case PhaseId.Fatal:
                    // Scope to the current tenant pass: a fatal DURING a tenant's
                    // run (e.g. "All packages have name collisions" for that
                    // tenant) must not fail packages that belong to other tenants
                    // and haven't run yet. Before any pass (auth/preflight fatal),
                    // _currentPassPackages is empty, so InCurrentPass is true for
                    // all and the fatal correctly fails the whole run.
                    foreach (var p in PackageProgressItems
                        .Where(p => (p.Outcome is PackageOutcome.Running or PackageOutcome.Pending)
                                    && InCurrentPass(p)))
                    {
                        p.Outcome = PackageOutcome.Failed;
                        p.FailureReason = evt.Detail ?? "Fatal error";
                        p.CurrentStepName = "Failed";
                    }
                    break;
            }
        });
    }

