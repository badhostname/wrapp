    /// <summary>
    /// Drives per-package progress from the module's structured
    /// <c>Write-WrappStep</c> events. Because each event carries the exact
    /// package + tenant it applies to, progress no longer relies on regex
    /// log-scraping with global (bleed-prone) mutators for the Intune path. The
    /// module-owned regex phases are suppressed while <see cref="_stepEventsOwnProgress"/>
    /// is set (see <see cref="OnPhaseChanged"/>); the vendored IntuneWin32App
    /// upload sub-steps and the Wrapping sub-steps still drive fine-grained
    /// progress within a package's "App Creation" / "Wrapping" step.
    ///
    /// Runs on the PS output-stream thread, so all UI mutation is marshalled to
    /// the dispatcher, exactly like <see cref="OnPhaseChanged"/>.
    /// </summary>
    private void HandleStepEvent(System.Management.Automation.PSObject obj, string tenantId)
    {
        var evt = Models.StepEvent.FromPSObject(obj);
        if (evt is null) return;

        var target = string.IsNullOrEmpty(evt.TenantId) ? tenantId : evt.TenantId;
        AppLogger.Info($"[STEP] {target}: {evt.Package} / {evt.Step} / {evt.Kind}"
            + (string.IsNullOrEmpty(evt.Error) ? "" : $" -- {evt.Error}")
            + (string.IsNullOrEmpty(evt.Detail) ? "" : $" ({evt.Detail})"));

        System.Windows.Application.Current.Dispatcher.Invoke(() => ApplyStepEvent(evt));
    }

    /// <summary>Maps a module step id to its <see cref="PackageProgress"/> step name.</summary>
    private static string? MapStepName(string step) => step switch
    {
        "Collision"    => "Collision Check",
        "Wrapping"     => "Wrapping",
        "AppCreation"  => "App Creation",
        "Dependencies" => "Dependencies",
        "Assignment"   => "Assignment",
        _              => null,
    };

    private void ApplyStepEvent(Models.StepEvent evt)
    {
        // Broadcast signals ('*') act on the whole current tenant pass.
        switch (evt.Step)
        {
            case "TenantPass":
                // The module owns the tenant loop and reports each
                // pass boundary; Detail carries the pass's package names
                // ('|'-separated). This replaces the .NET loop iteration as the
                // source of the per-pass progress scope (_currentPassPackages).
                if (evt.Kind == "Start")
                {
                    _currentPassPackages.Clear();
                    foreach (var n in (evt.Detail ?? "").Split('|', StringSplitOptions.RemoveEmptyEntries))
                        _currentPassPackages.Add(n.Trim());
                    AddLog($"[PHASE] Tenant pass started: {evt.TenantId} ({_currentPassPackages.Count} package(s))", "Info");
                }
                // Success/Fail: nothing to mutate -- the pass's RunComplete
                // already finalized its packages; the set stays scoped until
                // the next pass starts so late events can't bleed.
                return;

            case "Fatal":
                foreach (var p in PackageProgressItems
                    .Where(p => (p.Outcome is PackageOutcome.Running or PackageOutcome.Pending)
                                && InCurrentPass(p)))
                {
                    p.Outcome = PackageOutcome.Failed;
                    p.FailureReason = string.IsNullOrEmpty(evt.Error) ? "Fatal error" : evt.Error!;
                    p.CurrentStepName = "Failed";
                }
                return;

            case "RunComplete":
                FinalizeAllPackages();
                return;
        }

        // Broadcast step events (Package = '*'): a step shared by every package
        // in the current tenant pass (Wrapping -- one .intunewin per pass).
        if (evt.Package == "*")
        {
            var broadcastStep = MapStepName(evt.Step);
            if (broadcastStep is null) return;
            switch (evt.Kind)
            {
                case "Start":
                    SetGlobalStep(broadcastStep, StepState.Running);
                    break;
                case "Progress":
                    SetGlobalSubStep(broadcastStep, evt.Detail ?? broadcastStep, evt.Percent ?? 0);
                    break;
                case "Success":
                    SetGlobalStep(broadcastStep, StepState.Succeeded);
                    break;
                case "Fail":
                    SetGlobalStep(broadcastStep, StepState.Failed);
                    break;
            }
            return;
        }

        var pkg = FindPackage(evt.Package);
        if (pkg is null) return;

        var stepName = MapStepName(evt.Step);
        if (stepName is null) return;

        switch (evt.Kind)
        {
            case "Start":
                if (evt.Step == "AppCreation")
                {
                    // The vendored upload sub-steps (OnPhaseChanged) apply to the
                    // active package; set it here since the regex that used to do
                    // so is suppressed while StepEvents own progress.
                    _activePackageName = pkg.PackageName;
                    pkg.Outcome = PackageOutcome.Running;
                    pkg.DetailText = string.Empty;
                    pkg.FailureReason = string.Empty;
                    pkg.SubStepPercent = 0;
                }
                SetStep(pkg, stepName, StepState.Running);
                break;

            case "Progress":
            {
                // Sub-step refinement within a Running step (the vendored
                // upload pipeline, translated module-side). Detail is
                // "status" or "status|extra" (e.g. the Graph app id).
                var parts = (evt.Detail ?? "").Split('|', 2);
                pkg.CurrentStepName = parts[0];
                if (parts.Length > 1) pkg.DetailText = parts[1];
                if (evt.Percent is int pct) pkg.SubStepPercent = pct;
                RecalcProgress(pkg);
                break;
            }

            case "Success":
                if (evt.Step == "AppCreation")
                {
                    pkg.SubStepPercent = 0;
                    pkg.DetailText = string.Empty;
                }
                SetStep(pkg, stepName, StepState.Succeeded);
                break;

            case "Skip":
                SetStep(pkg, stepName, StepState.Skipped);
                break;

            case "Fail":
                pkg.Outcome = PackageOutcome.Failed;
                if (!string.IsNullOrEmpty(evt.Error))
                    pkg.FailureReason = evt.Error!;
                pkg.CurrentStepName = stepName == "Collision Check" ? "Collision" : "Failed";
                SetStep(pkg, stepName, StepState.Failed);
                break;
        }
    }

    private void CaptureEncryptionKeys(System.Management.Automation.PSObject obj, string tenantId)
    {
        if (_keyStore is null) return;
        try
        {
            var type = obj.Properties["_Type"]?.Value?.ToString();
            if (type != "EncryptionKeys") return;

            var keys = new Models.EncryptionKeyInfo
            {
                AppId                  = obj.Properties["AppId"]?.Value?.ToString() ?? "",
                DisplayName            = obj.Properties["DisplayName"]?.Value?.ToString() ?? "",
                TenantId               = obj.Properties["TenantId"]?.Value?.ToString() ?? tenantId,
                EncryptionKey          = obj.Properties["EncryptionKey"]?.Value?.ToString() ?? "",
                InitializationVector   = obj.Properties["InitializationVector"]?.Value?.ToString() ?? "",
                MacKey                 = obj.Properties["MacKey"]?.Value?.ToString() ?? "",
                Mac                    = obj.Properties["Mac"]?.Value?.ToString() ?? "",
                ProfileIdentifier      = obj.Properties["ProfileIdentifier"]?.Value?.ToString() ?? "ProfileVersion1",
                FileDigest             = obj.Properties["FileDigest"]?.Value?.ToString() ?? "",
                FileDigestAlgorithm    = obj.Properties["FileDigestAlgorithm"]?.Value?.ToString() ?? "SHA256",
                PackageName            = obj.Properties["PackageName"]?.Value?.ToString() ?? "",
                SetupFile              = obj.Properties["SetupFile"]?.Value?.ToString() ?? "",
                InnerFileName          = obj.Properties["InnerFileName"]?.Value?.ToString() ?? "",
                UnencryptedContentSize = long.TryParse(obj.Properties["UnencryptedContentSize"]?.Value?.ToString(), out var sz) ? sz : 0,
                SavedAt                = SystemClock.UtcNow.ToString("o"),
                SavedBy                = Environment.UserName,
            };

            if (string.IsNullOrEmpty(keys.AppId) || string.IsNullOrEmpty(keys.EncryptionKey)) return;

            // Silent-skip when the vault gate is OFF. The capture
            // path is invisible UI (fires-and-forgets during packaging), so
            // there's no button to grey out -- the gate check itself is the
            // entire opt-out surface for this flow. The "KEYS LOST" dialog
            // path below stays as a defensive net for code paths that reach
            // SaveKeysAsync without going through this guard.
            if (_featureGate is not null
                && !_featureGate.IsEnabled(Models.WrappFeatures.AzureDevOpsKeyVault))
            {
                AppLogger.Info($"[Run] Encryption keys captured for '{keys.DisplayName}' "
                    + $"({keys.AppId}) but vault gate is OFF -- keys not pushed. "
                    + $"Reason: {_featureGate.DescribeWhyDisabled(Models.WrappFeatures.AzureDevOpsKeyVault)}");
                return;
            }

            // Fire-and-forget -- don't block the packaging run
            _ = Task.Run(async () =>
            {
                try
                {
                    await _keyStore.SaveKeysAsync(keys);
                    AddLog($"[INFO] Encryption keys saved for '{keys.DisplayName}' ({keys.AppId})", "Info");
                }
                catch (Services.EncryptionKeyStoreService.DevOpsVaultNotConfiguredException)
                {
                    // The DevOps vault is the only place keys live now.
                    // With no vault configured, the keys are gone --
                    // call that out loudly so the user knows to configure
                    // Settings -> Key Vault before the next packaging run.
                    var msg = $"Encryption keys captured for '{keys.DisplayName}' ({keys.AppId}) "
                            + "but the Azure DevOps key vault is not configured -- KEYS LOST. "
                            + "Configure Settings -> Key Vault and re-run packaging to produce a fresh keypair.";
                    AppLogger.Warn($"[Run] {msg}");
                    AddLog($"[WARN] {msg}", "Warning");
                    try
                    {
                        var dispatcher = System.Windows.Application.Current?.Dispatcher;
                        if (dispatcher is not null)
                        {
                            await dispatcher.InvokeAsync(async () =>
                                await FluentDialog.ShowInfoAsync(
                                    "Encryption keys discarded",
                                    "Packaging captured encryption keys but the Azure DevOps key vault "
                                    + "is not configured. The keys have been discarded. Configure the vault "
                                    + "in Settings -> Key Vault, then re-run the packaging to produce a "
                                    + "fresh keypair."));
                        }
                    }
                    // must-stay-silent: the dialog is a courtesy on top of the
                    // already-logged WARN; if the UI thread is gone (shutdown)
                    // or the dispatcher rejects the dispatch, the WARN is the
                    // documented user signal.
                    catch { }
                }
                catch (Exception ex)
                {
                    // Persist to app.log as well as the (transient) run pane, so
                    // a vault push/PR failure stays diagnosable after the run
                    // window closes. The message carries the app id; the vault
                    // layer (EncryptionKeyStoreService) logs the DevOps server
                    // response separately.
                    AppLogger.Warn($"[Run] Failed to save encryption keys for "
                        + $"'{keys.DisplayName}' ({keys.AppId}): {ex.Message}");
                    AddLog($"[WARN] Failed to save encryption keys: {ex.Message}", "Warning");
                }
            });
        }
        catch { /* swallow -- key capture must never break the run */ }
    }

    private void WarnPastDates()
    {
        var now = SystemClock.UtcNow;
        var config = _appInfoVm.FullConfig;

        if (Target is RunTarget.Intune or RunTarget.Both)
        {
            foreach (var pkg in config.Script.IntunePackager.Packages)
            {
                foreach (var a in pkg.Assignments)
                {
                    CheckDate(a.AvailableTime, "AvailableTime", pkg.AppName, a.DisplayName, now);
                    CheckDate(a.DeadlineTime, "DeadlineTime", pkg.AppName, a.DisplayName, now);
                }
            }
        }

        if (Target is RunTarget.SCCM or RunTarget.Both)
        {
            foreach (var pkg in config.Script.SCCMPackager.Packages)
            {
                foreach (var d in pkg.Deployments)
                {
                    CheckDate(d.AvailableDateTime, "AvailableDateTime", pkg.AppName, d.DisplayName, now);
                    CheckDate(d.DeadlineDateTime, "DeadlineDateTime", pkg.AppName, d.DisplayName, now);
                }
            }
        }
    }

    private void CheckDate(string? value, string fieldName, string package, string entry, DateTime now)
    {
        if (string.IsNullOrEmpty(value)) return;
        // Skip ASAP sentinel
        if (value.StartsWith("0001-01-01")) return;

        if (DateTime.TryParse(value, System.Globalization.CultureInfo.InvariantCulture,
            System.Globalization.DateTimeStyles.AdjustToUniversal, out var dt) && dt < now)
        {
            AddLog($"[WARN] {package} / {entry}: {fieldName} is in the past ({dt:yyyy-MM-dd HH:mm} UTC) - will be treated as ASAP.", "Warning");
        }
    }

